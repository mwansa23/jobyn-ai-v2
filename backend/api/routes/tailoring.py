# The date on which CV validation became mandatory in the generation pipeline.
#
# Evidence: commit 4162ed0 introduced ``cv_validator.py`` and wired
# ``CVValidator.validate()`` into ``generate_tailored_cv()``.  Its author
# timestamp is 2026-11-17 16:46:54 +0200, which is 2026-11-17T14:46:54Z.
#
# Any TailoredCV row created before 14:46:54 UTC on 2026-11-17 was produced
# without a validator and legitimately lacks a ``validation`` key.  Using
# midnight (00:00:00Z) on that date as the cutoff would be 14 hours and 46
# minutes too early: rows generated by real users in that window would be
# incorrectly treated as post-enforcement and blocked from export.
#
# The cutoff is therefore set to the precise commit timestamp so that only
# rows that were genuinely produced after the validator existed are subject
# to enforcement.
#
# Deployment note: export enforcement itself (_check_export_allowed) has
# not been committed to the repository and is therefore not live in
# production.  No production data is affected by this constant until the
# working-tree changes are deployed.
#
# Legacy rows: the tailored_cvs table was created on 2026-11-05.  Any row
# with created_at < _VALIDATION_ENFORCEMENT_DATE is a genuine legacy row —
# the table existed but validation did not.
_VALIDATION_ENFORCEMENT_DATE = datetime.datetime(
    2026, 11, 17, 14, 46, 54, tzinfo=datetime.timezone.utc
)


def _check_export_allowed(cv: Any) -> None:
    """Raise HTTP 422 when the CV's validation result blocks export.

    States handled:

    1. No ``validation`` key, row pre-dates enforcement cutoff
       → **allow** (genuine legacy version, backward-compatible).
    2. No ``validation`` key, row on/after enforcement cutoff
       → **block 422** (pipeline bypass; must regenerate/re-edit).
    3. Malformed ``validation`` (not a dict, or missing required fields)
       → **block 422** (incomplete record; must regenerate/re-edit).
    4. ``skipped: True`` (validation crashed at save time)
       → **block 422** (unverified content; must regenerate/re-edit).
    5. ``is_valid: False`` (confirmed unsupported claims)
       → **block 422**.
    6. ``is_valid: True``, ``skipped: False`` or absent with valid structure
       (clean or warnings-only)
       → **allow**.
    """
    validation = (cv.content or {}).get("validation")

    if validation is None:
        # No validation record present.  Distinguish legacy from bypass.
        cv_created_at = getattr(cv, "created_at", None)
        if cv_created_at is not None:
            # Normalise to UTC-aware for comparison.
            if cv_created_at.tzinfo is None:
                cv_created_at = cv_created_at.replace(tzinfo=datetime.timezone.utc)
            if cv_created_at >= _VALIDATION_ENFORCEMENT_DATE:
                raise HTTPException(
                    status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                    detail=(
                        "This CV version has no validation record. "
                        "Please regenerate or re-edit the CV to run validation "
                        "before exporting."
                    ),
                )
        # Pre-enforcement legacy version — allow for backward compatibility.
        return

    # ── Structural validation of the validation record ───────────────────
    # An existing validation dict without ``skipped`` (from the committed code
    # before the field was added) is acceptable ONLY if its other fields are
    # present and correctly typed.  A missing or malformed validation record
    # must never pass as clean validation.
    if not isinstance(validation, dict):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "This CV version has a malformed validation record. "
                "Please regenerate or re-edit the CV before exporting."
            ),
        )
    if not isinstance(validation.get("is_valid"), bool):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "This CV version has an incomplete validation record "
                "(missing or invalid is_valid field). "
                "Please regenerate or re-edit the CV before exporting."
            ),
        )
    if not isinstance(validation.get("unsupported_claims"), list):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "This CV version has an incomplete validation record "
                "(missing or invalid unsupported_claims field). "
                "Please regenerate or re-edit the CV before exporting."
            ),
        )
    if not isinstance(validation.get("warnings"), list):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "This CV version has an incomplete validation record "
                "(missing or invalid warnings field). "
                "Please regenerate or re-edit the CV before exporting."
            ),
        )

    if validation.get("skipped"):
        # Validation was interrupted by a technical error.  The content is
        # unverified; block until the candidate regenerates or re-edits.
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "Validation of this CV version was interrupted by a technical "
                "error and cannot be verified. Please regenerate or re-edit the "
                "CV to run validation before exporting."
            ),
        )

    if not validation.get("is_valid", True):
        summary = validation.get("validation_summary", "")
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "This CV version contains unsupported claims and cannot be exported. "
                + (summary if summary else "Review the validation findings and edit before exporting.")
            ),
        )


